const EXTENSIONS = new Set(['.swift', '.ts', '.tsx']);
const GENERATED_MARKERS = [
  'auto-generated',
  'autogenerated',
  'auto generated',
  'do not edit',
  'generated by',
  '@generated',
];

const SHINGLE_SIZE = 5;
const MIN_SHINGLES = 20;
const MAX_POSTINGS = 60;
const MIN_SHARED_SHINGLES = 4;

const DECL_PATTERNS = [
  /^\s*(?:@\w+(?:\([^)]*\))?\s+)*(?:public\s+|internal\s+|private\s+|fileprivate\s+|open\s+)?(?:static\s+|class\s+|final\s+)?(?:override\s+)?func\s+([\w`]+)/,
  /^\s*(?:@\w+(?:\([^)]*\))?\s+)*(?:public\s+|internal\s+|private\s+|fileprivate\s+)?(?:convenience\s+|required\s+)?init\??\s*[(<]/,
  /^\s*(?:public\s+|internal\s+|private\s+|fileprivate\s+|open\s+)?(?:static\s+|class\s+)?var\s+(\w+)\s*:\s*[^={]+\{\s*$/,
  /^\s*(?:export\s+)?(?:default\s+)?(?:async\s+)?function\s+(\w+)/,
  /^\s*(?:export\s+)?const\s+(\w+)(?:\s*:\s*[^=]+)?\s*=\s*(?:async\s*)?(?:\([^;]*\)|\w+)\s*(?::[^=]+)?=>/,
];

function parseArgs(argv) {
  const opts = {
    diff: false,
    base: 'origin/master',
    minLines: 5,
    threshold: 0.75,
    limit: 12,
    json: false,
    all: false,
    tests: false,
    sameFile: false,
    selfTest: false,
  };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--help' || arg === '-h') {
      process.stdout.write(USAGE);
      process.exit(0);
    } else if (arg === '--diff') {
      opts.diff = true;
      if (argv[i + 1] && !argv[i + 1].startsWith('--')) opts.base = argv[++i];
    } else if (arg === '--min-lines') {
      opts.minLines = Number(argv[++i]);
    } else if (arg === '--threshold') {
      opts.threshold = Number(argv[++i]);
    } else if (arg === '--limit') {
      opts.limit = Number(argv[++i]);
    } else if (arg === '--json') {
      opts.json = true;
    } else if (arg === '--all') {
      opts.all = true;
    } else if (arg === '--tests') {
      opts.tests = true;
    } else if (arg === '--same-file') {
      opts.sameFile = true;
    } else if (arg === '--self-test') {
      opts.selfTest = true;
    } else {
      fail(`unknown option: ${arg}\n${USAGE}`);
    }
  }
  return opts;
}

function fail(message) {
  process.stderr.write(`${message}\n`);
  process.exit(2);
}

function git(args) {
  return execFileSync('git', args, {
    cwd: ROOT,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
}

function loadConfig() {
  if (!fs.existsSync(CONFIG_PATH))
    return { skipPaths: [], intentionalPairs: [], skipNames: [] };
  const raw = JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8'));
  return {
    skipPaths: (raw.skipPaths ?? []).map(globToRegExp),
    intentionalPairs: (raw.intentionalPairs ?? []).map((pair) => {
      const problem = validatePair(pair);
      if (problem) fail(`${CONFIG_PATH}: ${problem} — entry: ${JSON.stringify(pair)}`);
      return { reason: pair.reason, a: globToRegExp(pair.a), b: globToRegExp(pair.b) };
    }),
    skipNames: (raw.skipNames ?? []).map((source) => new RegExp(source)),
  };
}

function validatePair(pair) {
  if (!pair.a || !pair.b) return 'every intentionalPair needs both "a" and "b"';
  if ((pair.reason ?? '').trim().length < 20) {
    return 'every intentionalPair needs a reason explaining why the duplication is deliberate';
  }
  return null;
}

function globToRegExp(glob) {
  let out = '';
  let i = 0;
  while (i < glob.length) {
    if (glob.startsWith('**/', i)) {
      out += '(?:.*/)?';
      i += 3;
    } else if (glob.startsWith('**', i)) {
      out += '.*';
      i += 2;
    } else if (glob[i] === '*') {
      out += '[^/]*';
      i += 1;
    } else if (glob[i] === '?') {
      out += '.';
      i += 1;
    } else {
      out += glob[i].replace(/[.+^${}()|[\]\\]/, String.raw`\$&`);
      i += 1;
    }
  }
  return new RegExp(`^${out}$`);
}

function sourceFiles() {
  return git(['ls-files', '--cached', '--others', '--exclude-standard'])
    .split('\n')
    .filter((file) => file && EXTENSIONS.has(path.extname(file)));
}

function changedFiles(base, run = git) {
  let range;
  try {
    range = run(['merge-base', base, 'HEAD']).trim();
  } catch {
    range = null;
  }
  const committed = range
    ? run(['diff', '--name-only', '--diff-filter=ACMR', `${range}...HEAD`])
    : '';
  const working = run(['diff', '--name-only', '--diff-filter=ACMR', 'HEAD']);
  const untracked = run(['ls-files', '--others', '--exclude-standard']);
  return mergeChangedFiles(committed, working, untracked);
}

function mergeChangedFiles(...outputs) {
  return new Set(
    outputs
      .join('\n')
      .split('\n')
      .map((file) => file.trim())
      .filter((file) => file && EXTENSIONS.has(path.extname(file))),
  );
}

function isGenerated(text) {
  const head = text.slice(0, 500).toLowerCase();
  return GENERATED_MARKERS.some((marker) => head.includes(marker));
}

function stripNoise(source, keepStrings = false) {
  let out = '';
  let i = 0;
  const n = source.length;
  while (i < n) {
    const two = source.slice(i, i + 2);
    if (two === '//') {
      while (i < n && source[i] !== '\n') i++;
    } else if (two === '/*') {
      i += 2;
      while (i < n && source.slice(i, i + 2) !== '*/') i++;
      i += 2;
    } else if (source.slice(i, i + 3) === '"""') {
      const start = i;
      i += 3;
      while (i < n && source.slice(i, i + 3) !== '"""') i++;
      i += 3;
      out += keepStrings ? source.slice(start, i) : '"S"';
    } else if (source[i] === '"' || source[i] === '`' || source[i] === "'") {
      const quote = source[i];
      const start = i;
      i++;
      while (i < n && source[i] !== quote) {
        if (source[i] === '\\') i++;
        i++;
      }
      i++;
      out += keepStrings ? source.slice(start, i) : '"S"';
    } else {
      out += source[i];
      i++;
    }
  }
  return out;
}

function declarationBounds(lines, start) {
  let depth = 0;
  let opened = false;
  for (let i = start; i < lines.length; i++) {
    const scrubbed = stripNoise(lines[i]);
    for (const ch of scrubbed) {
      if (ch === '{') {
        depth++;
        opened = true;
      } else if (ch === '}') {
        depth--;
      }
    }
    if (opened && depth <= 0) return i;
    if (i - start > 400) return -1;
  }
  return -1;
}

function declarationName(line) {
  for (const pattern of DECL_PATTERNS) {
    const match = pattern.exec(line);
    if (match) return (match[1] ?? 'init').replace(/`/g, '');
  }
  return null;
}

function extractDeclarations(file, text, minLines) {
  const lines = text.split('\n');
  const decls = [];
  for (let i = 0; i < lines.length; i++) {
    const name = declarationName(lines[i]);
    if (!name) continue;
    const end = declarationBounds(lines, i);
    if (end < 0) continue;
    const lineCount = end - i + 1;
    if (lineCount < minLines) {
      i = end;
      continue;
    }
    const previous = i > 0 ? lines[i - 1] : '';
    if (!/dup-ok/i.test(previous)) {
      const body = lines.slice(i, end + 1).join('\n');
      decls.push({ file, name, line: i + 1, lineCount, body });
    }
    i = end;
  }
  return decls;
}

function normalize(body) {
  return stripNoise(body, true).replace(/\s+/g, ' ').trim();
}

const TOKEN = /[A-Za-z_][A-Za-z0-9_]*|\d+|[{}()[\].,:=<>!&|+\-*/?]/g;

function shingles(normalized) {
  const tokens = normalized.match(TOKEN) ?? [];
  const set = new Set();
  for (let i = 0; i + SHINGLE_SIZE <= tokens.length; i++) {
    set.add(tokens.slice(i, i + SHINGLE_SIZE).join('\u0001'));
  }
  return set;
}

function jaccard(a, b) {
  let intersection = 0;
  const [small, large] = a.size <= b.size ? [a, b] : [b, a];
  for (const item of small) if (large.has(item)) intersection++;
  return intersection / (a.size + b.size - intersection);
}

function isIntentional(config, members) {
  const files = [...new Set(members.map((m) => m.file))];
  for (const { a, b } of config.intentionalPairs) {
    const spansPair = files.some((x) =>
      files.some((y) => x !== y && a.test(x) && b.test(y)),
    );
    if (spansPair) return true;
  }
  return members.every((m) => config.skipNames.some((re) => re.test(m.name)));
}

function collect(opts, config) {
  const decls = [];
  for (const file of sourceFiles()) {
    if (config.skipPaths.some((re) => re.test(file))) continue;
    let text;
    try {
      text = fs.readFileSync(path.join(ROOT, file), 'utf8');
    } catch {
      continue;
    }
    if (isGenerated(text)) continue;
    for (const decl of extractDeclarations(file, text, opts.minLines)) {
      decl.normalized = normalize(decl.body);
      if (decl.normalized.length < 60) continue;
      decl.shingles = shingles(decl.normalized);
      decls.push(decl);
    }
  }
  return decls;
}

function exactGroups(decls) {
  const byHash = new Map();
  for (const decl of decls) {
    const hash = crypto.createHash('md5').update(decl.normalized).digest('hex');
    if (!byHash.has(hash)) byHash.set(hash, []);
    byHash.get(hash).push(decl);
  }
  const groups = [];
  for (const members of byHash.values()) {
    if (members.length < 2) continue;
    groups.push({ kind: 'exact', similarity: 1, members });
  }
  return groups;
}

function nearPairs(decls, exactHashes, threshold) {
  const postings = new Map();
  decls.forEach((decl, index) => {
    if (decl.shingles.size < MIN_SHINGLES) return;
    for (const shingle of decl.shingles) {
      if (!postings.has(shingle)) postings.set(shingle, []);
      postings.get(shingle).push(index);
    }
  });

  const candidates = new Map();
  for (const indexes of postings.values()) {
    if (indexes.length > MAX_POSTINGS) continue;
    for (let a = 0; a < indexes.length; a++) {
      for (let b = a + 1; b < indexes.length; b++) {
        const key = indexes[a] * decls.length + indexes[b];
        candidates.set(key, (candidates.get(key) ?? 0) + 1);
      }
    }
  }

  const pairs = [];
  for (const [key, shared] of candidates) {
    if (shared < MIN_SHARED_SHINGLES) continue;
    const a = Math.floor(key / decls.length);
    const b = key % decls.length;
    if (exactHashes.has(`${a}:${b}`)) continue;
    const similarity = jaccard(decls[a].shingles, decls[b].shingles);
    if (similarity < threshold) continue;
    pairs.push([a, b, similarity]);
  }
  return clusterPairs(decls, pairs);
}

function clusterPairs(decls, pairs) {
  const parent = new Map();
  const find = (x) => {
    while (parent.get(x) !== x) {
      parent.set(x, parent.get(parent.get(x)));
      x = parent.get(x);
    }
    return x;
  };
  for (const [a, b] of pairs) {
    if (!parent.has(a)) parent.set(a, a);
    if (!parent.has(b)) parent.set(b, b);
    const rootA = find(a);
    const rootB = find(b);
    if (rootA !== rootB) parent.set(rootA, rootB);
  }

  const clusters = new Map();
  const weakest = new Map();
  for (const [a, b, similarity] of pairs) {
    const root = find(a);
    if (!clusters.has(root)) clusters.set(root, new Set());
    clusters.get(root).add(a);
    clusters.get(root).add(b);
    weakest.set(root, Math.min(weakest.get(root) ?? 1, similarity));
  }

  return [...clusters].map(([root, indexes]) => ({
    kind: 'near',
    similarity: weakest.get(root),
    members: [...indexes].sort((x, y) => x - y).map((index) => decls[index]),
  }));
}

function redundantLines(group) {
  const lines = Math.min(...group.members.map((m) => m.lineCount));
  return (group.members.length - 1) * lines;
}

function dropSubsumed(exact, near) {
  const key = (member) => `${member.file}:${member.line}`;
  const nearSets = near.map((group) => new Set(group.members.map(key)));
  return exact.filter(
    (group) =>
      !nearSets.some((set) => group.members.every((member) => set.has(key(member)))),
  );
}

function isCrossFile(group) {
  return new Set(group.members.map((m) => m.file)).size > 1;
}

const moduleCache = new Map();

function moduleOf(file) {
  if (moduleCache.has(file)) return moduleCache.get(file);
  let name;
  const swift = /^(.*?)\/(?:Sources|Tests)\/([^/]+)\//.exec(file);
  if (swift) {
    name = swift[2];
  } else {
    let dir = path.dirname(file);
    while (dir && dir !== '.' && !fs.existsSync(path.join(ROOT, dir, 'package.json'))) {
      dir = path.dirname(dir);
    }
    name = dir === '.' ? 'root' : dir;
  }
  moduleCache.set(file, name);
  return name;
}

function modulesOf(group) {
  return [...new Set(group.members.map((m) => moduleOf(m.file)))];
}

const DRIFT_SIMILARITY = 0.9;
const DRIFT_NEAR_SIMILARITY = 0.8;
const DRIFT_MAX_LINES = 50;

const TIERS = [
  {
    name: 'mechanical',
    blurb:
      'identical bodies — evaluate these first. a move within one module is safe; across modules, check the dependency graph before deciding',
    complete: true,
  },
  {
    name: 'drifted',
    blurb:
      'near-identical copies of one thing that have diverged — decide which behavior is correct, do not merge blindly',
    complete: false,
  },
  {
    name: 'design',
    blurb: 'shared structure worth unifying, but a real refactor — give it its own diff',
    complete: false,
  },
  {
    name: 'same-file',
    blurb: 'repetition within one file — usually enumerated cases, usually leave alone',
    complete: false,
  },
];

const GATE_DRIFT_SIMILARITY = 0.9;

function isBlocking(group) {
  const tier = tierOf(group);
  if (tier === 'mechanical') return true;
  return tier === 'drifted' && group.similarity >= GATE_DRIFT_SIMILARITY;
}

function tierOf(group) {
  if (!isCrossFile(group)) return 'same-file';
  if (group.kind === 'exact') return 'mechanical';
  if (group.similarity >= DRIFT_SIMILARITY) return 'drifted';
  const largest = Math.max(...group.members.map((m) => m.lineCount));
  if (largest <= DRIFT_MAX_LINES && group.similarity >= DRIFT_NEAR_SIMILARITY) {
    return 'drifted';
  }
  return 'design';
}

function isTestFile(file) {
  return /(^|\/)(Tests?|__tests__)\//.test(file) || /\.(test|spec)\.tsx?$/.test(file);
}

function rank(a, b) {
  return redundantLines(b) - redundantLines(a);
}

function report(groups, opts, stats) {
  const crossFile = groups.filter(isCrossFile);
  const lines = [];
  lines.push('');
  lines.push(
    `scanned ${stats.files} files, ${stats.decls} declarations` +
      (opts.diff ? ` (diff vs ${opts.base}: ${stats.changed} files changed)` : ''),
  );
  lines.push(
    `${crossFile.length} cross-file clone group${crossFile.length === 1 ? '' : 's'} ` +
      `(~${crossFile.reduce((sum, group) => sum + redundantLines(group), 0)} redundant lines), ` +
      `${groups.length - crossFile.length} same-file` +
      (stats.ignored ? `, ${stats.ignored} ignored as intentional` : ''),
  );

  for (const tier of TIERS) {
    const inTier = groups.filter((group) => tierOf(group) === tier.name);
    if (inTier.length === 0) continue;

    if (tier.name === 'same-file' && !opts.sameFile) {
      lines.push('');
      lines.push(
        `── same-file · ${inTier.length} groups — ${tier.blurb.split(' — ')[1]}. ` +
          `pass --same-file to list ──`,
      );
      continue;
    }

    const shown = tier.complete ? inTier : inTier.slice(0, opts.limit);
    lines.push('');
    lines.push(`── ${tier.name} · ${inTier.length} groups · ${tier.blurb} ──`);

    for (const group of shown) {
      const tag =
        group.kind === 'exact' ? 'exact' : `${(group.similarity * 100).toFixed(0)}%`;
      lines.push('');
      lines.push(
        `  ~${redundantLines(group)}L  [${group.members.length}x ${tag}]  ${group.members[0].name}`,
      );
      for (const member of group.members.slice(0, 6)) {
        lines.push(`      ${member.file}:${member.line}  (${member.lineCount} lines)`);
      }
      if (group.members.length > 6) {
        lines.push(`      … and ${group.members.length - 6} more copies`);
      }
      const modules = modulesOf(group);
      if (modules.length > 1) {
        lines.push(
          `      ! spans ${modules.length} modules (${modules.join(', ')}) — ` +
            `check for an existing shared target both already depend on`,
        );
      }
    }

    if (inTier.length > shown.length) {
      lines.push('');
      lines.push(`  … ${inTier.length - shown.length} more (raise --limit to see them)`);
    }
  }

  lines.push('');
  return lines.join('\n');
}

function selfTest() {
  const failures = [];
  let ran = 0;
  const ok = (name, condition, detail = '') => {
    ran++;
    if (!condition) failures.push(`${name}${detail ? `  (${detail})` : ''}`);
  };
  const decl = (file, name, lineCount = 10) => ({ file, name, lineCount, line: 1 });
  const group = (kind, similarity, members) => ({ kind, similarity, members });

  const source = fs.readFileSync(fileURLToPath(import.meta.url));
  const control = [...source].filter((b) => b < 0x20 && b !== 9 && b !== 10 && b !== 13);
  ok(
    'source file contains no raw control bytes',
    control.length === 0,
    control.length
      ? `found ${control.map((b) => `0x${b.toString(16).padStart(2, '0')}`).join(', ')} — ` +
          'invisible in editors, and a NUL makes git treat the script as binary. ' +
          'spell control characters as escapes like \\u0001'
      : '',
  );

  ok(
    'working-tree-only changes reach the diff gate',
    mergeChangedFiles('', 'swift/a/W.swift\n', '').has('swift/a/W.swift'),
    'just dup --diff would report a false clean while you have uncommitted edits',
  );
  ok(
    'committed, working-tree and untracked changes are unioned',
    mergeChangedFiles('swift/a/C.swift', 'swift/a/W.swift', 'swift/a/U.swift').size === 3,
  );
  ok(
    'the same file from two sources is counted once',
    mergeChangedFiles('swift/a/C.swift', 'swift/a/C.swift', '').size === 1,
  );
  ok(
    'non-source files are excluded from the diff set',
    mergeChangedFiles('README.md\nweb/a.tsx', '', '').size === 1,
  );

  const fakeGit = (args) => {
    if (args[0] === 'merge-base') return 'base0\n';
    if (args[0] === 'ls-files') return 'swift/a/Untracked.swift\n';
    if (args.includes('base0...HEAD')) return 'swift/a/Committed.swift\n';
    return 'swift/a/Working.swift\n';
  };
  const seen = changedFiles('origin/master', fakeGit);
  ok(
    'changedFiles wires the working-tree diff in',
    seen.has('swift/a/Working.swift'),
    'just dup --diff would report a false clean while you have uncommitted edits',
  );
  ok('changedFiles wires the committed range in', seen.has('swift/a/Committed.swift'));
  ok('changedFiles wires untracked files in', seen.has('swift/a/Untracked.swift'));

  const sqlA = 'func q() {\n  SQL("""\n  WHERE id = \'aaa\'\n  """)\n}';
  const sqlB = 'func q() {\n  SQL("""\n  WHERE id = \'bbb\'\n  """)\n}';
  ok(
    'string literals are compared, not blanked, for exact matches',
    normalize(sqlA) !== normalize(sqlB),
    'two queries differing only in SQL would be reported as byte-identical',
  );
  ok(
    'string literals are blanked for structural matching',
    stripNoise(sqlA, false) === stripNoise(sqlB, false),
  );
  ok('comments are stripped', normalize('a // note\nb') === normalize('a\nb'));

  ok('**/ matches nested', globToRegExp('**/Package.swift').test('a/b/Package.swift'));
  ok('**/ matches root', globToRegExp('**/Package.swift').test('Package.swift'));
  ok('dir/** matches under dir', globToRegExp('a/b/**').test('a/b/c/d.swift'));
  ok('dir/** does not escape dir', !globToRegExp('a/b/**').test('a/c/d.swift'));
  ok('* does not cross slashes', !globToRegExp('a/*.swift').test('a/b/c.swift'));
  ok('dots are escaped', !globToRegExp('a/x.swift').test('a/xyswift'));

  const selfRef = {
    intentionalPairs: [{ a: globToRegExp('t/**'), b: globToRegExp('t/**') }],
    skipNames: [],
  };
  ok(
    'a self-referential pair does not suppress same-file groups',
    !isIntentional(selfRef, [decl('t/x.swift', 'a'), decl('t/x.swift', 'b')]),
  );
  ok(
    'a self-referential pair does suppress cross-file groups it covers',
    isIntentional(selfRef, [decl('t/x.swift', 'a'), decl('t/y.swift', 'a')]),
  );
  ok(
    'a pair does not suppress unrelated files',
    !isIntentional(selfRef, [decl('u/x.swift', 'a'), decl('u/y.swift', 'a')]),
  );

  ok('pair with no reason is rejected', validatePair({ a: 'x', b: 'y' }) !== null);
  ok(
    'pair with a stub reason is rejected',
    validatePair({ a: 'x', b: 'y', reason: 'nope' }) !== null,
  );
  ok(
    'pair with a real reason is accepted',
    validatePair({ a: 'x', b: 'y', reason: 'a genuine explanation of the decision' }) ===
      null,
  );

  ok(
    'identical across files is mechanical',
    tierOf(group('exact', 1, [decl('a/x.swift', 'f'), decl('b/y.swift', 'f')])) ===
      'mechanical',
  );
  ok(
    'very similar across files is drifted',
    tierOf(group('near', 0.99, [decl('a/x.swift', 'f'), decl('b/y.swift', 'f')])) ===
      'drifted',
  );
  ok(
    'a small diverged helper is drifted, not design',
    tierOf(
      group('near', 0.81, [decl('a/x.swift', 'f', 43), decl('b/y.swift', 'f', 37)]),
    ) === 'drifted',
  );
  ok(
    'a large loosely-similar pair is design',
    tierOf(
      group('near', 0.79, [decl('a/x.swift', 'f', 90), decl('b/y.swift', 'f', 87)]),
    ) === 'design',
  );
  ok(
    'repetition inside one file is same-file',
    tierOf(group('exact', 1, [decl('a/x.swift', 'f'), decl('a/x.swift', 'f')])) ===
      'same-file',
  );

  ok(
    'gate blocks identical cross-file clones',
    isBlocking(group('exact', 1, [decl('a/x.swift', 'f'), decl('b/y.swift', 'f')])),
  );
  ok(
    'gate blocks a lightly-edited paste',
    isBlocking(group('near', 0.92, [decl('a/x.swift', 'f'), decl('b/y.swift', 'f')])),
  );
  ok(
    'gate does not block a small helper that merely diverged',
    !isBlocking(
      group('near', 0.81, [decl('a/x.swift', 'f', 43), decl('b/y.swift', 'f', 37)]),
    ),
  );
  ok(
    'gate never blocks design-tier similarity',
    !isBlocking(
      group('near', 0.79, [decl('a/x.swift', 'f', 90), decl('b/y.swift', 'f', 87)]),
    ),
  );
  ok(
    'gate never blocks same-file repetition',
    !isBlocking(group('exact', 1, [decl('a/x.swift', 'f'), decl('a/x.swift', 'f')])),
  );

  const swift = [
    'func alpha(a: Int) -> Int {',
    '  let s = "}"',
    '  return a',
    '}',
    '',
    'private func beta() {',
    '  // }',
    '  print(1)',
    '  print(2)',
    '}',
    '',
    '// dup-ok: deliberate',
    'func gamma() {',
    '  print(3)',
    '  print(4)',
    '  print(5)',
    '}',
  ].join('\n');
  const found = extractDeclarations('x.swift', swift, 4);
  ok(
    'extracts swift funcs',
    found.length === 2,
    `got ${found.map((d) => d.name).join(',')}`,
  );
  ok('braces inside strings do not end a declaration', found[0]?.lineCount === 4);
  ok('braces inside comments do not end a declaration', found[1]?.lineCount === 5);
  ok('dup-ok suppresses a declaration', !found.some((d) => d.name === 'gamma'));

  const ts =
    'export const useThing = (q: string): boolean => {\n  const a = 1;\n  const b = 2;\n  return true;\n};';
  ok(
    'extracts ts arrow consts',
    extractDeclarations('x.ts', ts, 4)[0]?.name === 'useThing',
  );

  ok(
    'swift module is the target dir',
    moduleOf('swift/macapp/App/Tests/AppTests/A.swift') === 'AppTests',
  );
  ok(
    'separate test targets are separate modules',
    moduleOf('swift/macapp/App/Tests/AppTests/A.swift') !==
      moduleOf('swift/macapp/App/Tests/FilterTests/B.swift'),
  );

  ok('test files are recognised', isTestFile('swift/api/Tests/ApiTests/A.swift'));
  ok('spec files are recognised', isTestFile('web/x/a.test.ts'));
  ok('source files are not test files', !isTestFile('swift/api/Sources/Api/A.swift'));

  const identical = shingles(normalize('func f() { print(1); print(2); print(3) }'));
  ok('jaccard of a set with itself is 1', jaccard(identical, identical) === 1);

  if (failures.length) {
    process.stdout.write(`\n${failures.length} of ${ran} self-tests FAILED:\n`);
    for (const failure of failures) process.stdout.write(`  ✗ ${failure}\n`);
    process.stdout.write('\n');
    process.exit(1);
  }
  process.stdout.write(`\nall ${ran} self-tests passed\n\n`);
}

function main() {
  const opts = parseArgs(process.argv.slice(2));
  if (opts.selfTest) {
    selfTest();
    return;
  }
  const config = loadConfig();
  const decls = collect(opts, config);
  const files = new Set(decls.map((d) => d.file)).size;

  const indexOf = new Map(decls.map((decl, index) => [decl, index]));
  const exact = exactGroups(decls);
  const exactHashes = new Set();
  for (const group of exact) {
    const indexes = group.members.map((m) => indexOf.get(m)).sort((a, b) => a - b);
    for (let a = 0; a < indexes.length; a++) {
      for (let b = a + 1; b < indexes.length; b++) {
        exactHashes.add(`${indexes[a]}:${indexes[b]}`);
      }
    }
  }

  const near = nearPairs(decls, exactHashes, opts.threshold);
  let groups = [...dropSubsumed(exact, near), ...near];

  let ignored = 0;
  if (!opts.all) {
    groups = groups.filter((group) => {
      if (isIntentional(config, group.members)) {
        ignored++;
        return false;
      }
      return true;
    });
  }

  let changed = 0;
  if (opts.diff) {
    const touched = changedFiles(opts.base);
    changed = touched.size;
    groups = groups.filter(
      (group) => group.members.some((m) => touched.has(m.file)) && isCrossFile(group),
    );
  }

  if (opts.tests) {
    groups = groups.filter((group) => group.members.every((m) => isTestFile(m.file)));
  }

  groups.sort(rank);

  if (opts.json) {
    process.stdout.write(
      `${JSON.stringify(
        {
          groups: groups.map((group) => ({
            tier: tierOf(group),
            modules: modulesOf(group),
            kind: group.kind,
            similarity: group.similarity,
            redundantLines: redundantLines(group),
            members: group.members.map(({ file, name, line, lineCount }) => ({
              file,
              name,
              line,
              lineCount,
            })),
          })),
        },
        null,
        2,
      )}\n`,
    );
  } else {
    process.stdout.write(
      report(groups, opts, { files, decls: decls.length, ignored, changed }),
    );
  }

  if (opts.diff && groups.length > 0) {
    const blocking = groups.filter(isBlocking);
    if (blocking.length === 0) {
      process.stderr.write(
        `\n${groups.length} clone group${groups.length === 1 ? '' : 's'} involving files this ` +
          'branch changed, but none are close enough to be a fresh copy-paste.\n' +
          'reported for your judgement; not failing the build.\n\n',
      );
      return;
    }
    process.stderr.write(
      `\n${blocking.length} of ${groups.length} clone group` +
        `${groups.length === 1 ? '' : 's'} ` +
        `${blocking.length === 1 ? 'looks' : 'look'} like a fresh copy-paste ` +
        `(identical, or >=${GATE_DRIFT_SIMILARITY * 100}% similar across files):\n` +
        blocking
          .map(
            (group) =>
              `  ${group.members[0].name} — ` +
              group.members.map((m) => `${m.file}:${m.line}`).join(', '),
          )
          .join('\n') +
        '\n\nextract the shared code, or declare it intentional in\n' +
        '.agents/skills/duplication/duplication-ignore.json, or with a\n' +
        '"dup-ok: <reason>" comment above the declaration.\n\n',
    );
    process.exit(1);
  }
}

main();
